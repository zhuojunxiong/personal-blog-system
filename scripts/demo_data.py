def create_demo_data():
    app = create_app()
    with app.app_context():
        db.create_all()

        users = []
        for uname, email, nick, bio in USERS:
            u = User.query.filter_by(username=uname).first()
            if not u:
                role = "admin" if uname == "admin" else "user"
                u = User(username=uname, email=email, nickname=nick, bio=bio, role=role, status="active")
                u.set_password("admin123456" if role == "admin" else "user123456")
                db.session.add(u)
                db.session.flush()
            users.append(u)

        cats = {}
        for name, desc, order in CATS:
            c = Category.query.filter_by(name=name).first()
            if not c:
                c = Category(name=name, description=desc, sort_order=order)
                db.session.add(c)
                db.session.flush()
            cats[name] = c

        tag_objs = {}
        for tn in TAGS:
            t = Tag.query.filter_by(name=tn).first()
            if not t:
                t = Tag(name=tn)
                db.session.add(t)
                db.session.flush()
            tag_objs[tn] = t

        cols = []
        for ui, cname, cdesc in COLS:
            if cname is None:
                cols.append(None)
            else:
                c = BlogColumn.query.filter_by(user_id=users[ui].id, name=cname).first()
                if not c:
                    c = BlogColumn(user_id=users[ui].id, name=cname, description=cdesc, status="active")
                    db.session.add(c)
                    db.session.flush()
                cols.append(c)

        articles = []
        for ui, cat_name, tag_names, title, summary, content, days, views in ART:
            existing = Article.query.filter_by(title=title).first()
            if existing:
                articles.append(existing)
                continue
            article = Article(
                title=title, slug=make_slug(title), summary=summary, content=content,
                status=ARTICLE_STATUS_PUBLISHED, user=users[ui],
                column=cols[ui] if ui < len(cols) else None,
                category=cats[cat_name], author=users[ui].nickname,
                view_count=views, published_at=utcnow() - timedelta(days=days),
            )
            article.tags = [tag_objs[tn] for tn in tag_names if tn in tag_objs]
            db.session.add(article)
            db.session.flush()
            articles.append(article)

        # 评论
        if not Comment.query.first():
            SAMPLE = [
                "写得太好了这个视角我之前完全没想到。",
                "刚好最近就在找这方面的内容雪中送炭。",
                "作为同行深有同感特别是那几条实操建议。",
                "收藏了回头实践一下再来反馈。",
                "能再展开讲讲吗比如具体怎么操作。",
                "这个问题困扰我很久了终于有人讲清楚了。",
                "不同行业的视角互相碰撞真的太有意思了。",
                "从头到尾读完每个例子都很扎实。",
                "建议加上相关案例的链接方便延伸阅读。",
                "总结得很到位我转发给团队了。",
            ]
            cmt_count = 0
            for _ in range(300):
                a = random.choice(articles)
                u = random.choice(users)
                db.session.add(Comment(
                    article=a, user=u, nickname=u.nickname, email=u.email,
                    content=random.choice(SAMPLE), status=COMMENT_STATUS_APPROVED,
                ))
                cmt_count += 1
            db.session.flush()

        # 点赞收藏
        like_count = fav_count = 0
        for article in articles[:180]:
            likers = random.sample(users, min(random.randint(5, 16), len(users)))
            for u in likers:
                if not Like.query.filter_by(user_id=u.id, article_id=article.id).first():
                    db.session.add(Like(user=u, article=article))
                    article.like_count += 1
                    like_count += 1
                if random.random() < 0.5:
                    if not Favorite.query.filter_by(user_id=u.id, article_id=article.id).first():
                        db.session.add(Favorite(user=u, article=article))
                        article.favorite_count += 1
                        fav_count += 1

        if not AiLog.query.first():
            db.session.add(AiLog(article=articles[0], scene="placeholder",
                input_text="V0.5.1 AI 智能搜索和六大写作功能已就绪。",
                ai_output="AI 功能已开放。"))

        db.session.commit()
        ac = Article.query.count()
        cc = Comment.query.count()
